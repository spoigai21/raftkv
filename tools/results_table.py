#!/usr/bin/env python3
"""Generates every measured number shown in the docs from the CSV files.

    python3 tools/results_table.py          # rewrite docs/results.md and the README's summary
    python3 tools/results_table.py --check  # fail if either is out of date (CI)

Inputs:
  docs/results.csv          the current measurements (tools/bench/run_all.py writes it)
  docs/results-phase9.csv   the Phase 9 measurements, frozen: the predictions in raftkv.md
                            were made about that version, so they are scored against it

Outputs:
  docs/results.md           all the tables, generated in full
  README.md                 a short summary, between the results markers

Nothing in either is typed by hand, so the write-up cannot drift from the measurements.
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
RESULTS_MD = ROOT / "docs/results.md"
CURRENT = ROOT / "docs/results.csv"
BASELINE = ROOT / "docs/results-phase9.csv"
BEGIN = "<!-- results:begin (generated by tools/results_table.py from docs/results.csv; do not edit) -->"
END = "<!-- results:end -->"


class Data:
    def __init__(self, path):
        self.rows = list(csv.DictReader(open(path, newline=""))) if path.exists() else []

    def get(self, e, v, m):
        return next((r["value"] for r in self.rows if r["experiment"] == e and r["variant"] == v and r["metric"] == m), None)

    def f(self, e, v, m):
        x = self.get(e, v, m)
        return float(x) if x is not None else None

    def variants(self, e):
        return list(dict.fromkeys(r["variant"] for r in self.rows if r["experiment"] == e))

    def first_variant(self, e):
        return next(iter(self.variants(e)), "")


def num(x, digits=0):
    return "–" if x is None else f"{float(x):,.{digits}f}"


def machine(d):
    power = d.get("machine", "power", "source")
    return (f"{d.get('machine', 'cpu', 'model')}, {d.get('machine', 'cpu', 'cores')} cores, "
            f"{d.get('machine', 'memory', 'size')} GiB, {d.get('machine', 'os', 'name')}, "
            f"measured {d.get('machine', 'date', 'measured')}" + (f" on {power} power" if power else ""))


def results_md(cur, base):
    o = ["# Results", "",
         "*Generated by `tools/results_table.py` from `docs/results.csv` and `docs/results-phase9.csv`. "
         "Do not edit by hand: rerun `python3 tools/bench/run_all.py`, then the generator.*", ""]
    o += [f"Measured on {machine(cur)}. Real `raftkvd` processes on one machine, driven by `raftkvload` "
          "(closed-loop clients, 16-byte values), durable fsync unless stated. Throughput figures are the "
          "median of three 10 s runs (build-type rows: one run). They compare configurations on this laptop; "
          "they are not a claim about production hardware.", ""]

    o += ["## Throughput and latency", "",
          "| Cluster size (writes, 32 clients) | Throughput | Write p50 | Write p99 |", "|---|---|---|---|"]
    for v in cur.variants("cluster_size"):
        o.append(f"| {v} | {num(cur.f('cluster_size', v, 'ops_per_sec'))} ops/s | "
                 f"{num(cur.f('cluster_size', v, 'write_p50'), 1)} ms | {num(cur.f('cluster_size', v, 'write_p99'), 1)} ms |")
    v = "3 nodes, 50% writes"
    o += ["", "| Reads vs writes (3 nodes, 8 clients, 50% writes) | p50 | p99 |", "|---|---|---|",
          f"| Get (through the log) | {num(cur.f('read_write_latency', v, 'read_p50'), 1)} ms | {num(cur.f('read_write_latency', v, 'read_p99'), 1)} ms |",
          f"| Put | {num(cur.f('read_write_latency', v, 'write_p50'), 1)} ms | {num(cur.f('read_write_latency', v, 'write_p99'), 1)} ms |", ""]

    o += ["## Under failure and by configuration", "", "| Measurement | Result |", "|---|---|"]
    fv = cur.first_variant("leader_failover")
    o.append(f"| Writes resume after `kill -9` of the leader ({fv}) | median {num(cur.f('leader_failover', fv, 'median'))} ms, "
             f"worst {num(cur.f('leader_failover', fv, 'max'))} ms |")
    md = cur.f("minority_down", "3 nodes, 1 follower stopped", "ops_per_sec")
    if md:
        o.append(f"| One follower stopped (`SIGSTOP`; stands in for a minority partition) | {num(md)} ops/s, "
                 f"vs {num(cur.f('cluster_size', '3 nodes', 'ops_per_sec'))} with all three |")
    g0, g1 = cur.f("group_commit", "off (one fsync per request)", "ops_per_sec"), cur.f("group_commit", "on (one fsync per batch)", "ops_per_sec")
    if g0 and g1:
        o.append(f"| Group commit: one fsync per batch vs per request | {num(g1)} vs {num(g0)} ops/s (**{g1 / g0:.1f}×**) |")
    b1, b64 = cur.f("batching", "max 1 entry per RPC", "ops_per_sec"), cur.f("batching", "max 64 entries per RPC", "ops_per_sec")
    if b1 and b64:
        o.append(f"| Batching: up to 64 entries per `AppendEntries` vs 1 | {num(b64)} vs {num(b1)} ops/s (**{b64 / b1:.1f}×**) |")
    f1, f0 = cur.f("fsync", "durable (fsync)", "ops_per_sec"), cur.f("fsync", "no fsync (unsafe)", "ops_per_sec")
    if f1 and f0:
        o.append(f"| Durable fsync vs none (unsafe) | {num(f1)} vs {num(f0)} ops/s |")
    for bv in cur.variants("build_type"):
        o.append(f"| Servers built {bv} | {num(cur.f('build_type', bv, 'ops_per_sec'))} ops/s |")
    kept = cur.f("message_drops", "20% drops, simulated", "throughput_kept")
    if kept:
        o.append(f"| 20% message drops (simulator, virtual time) | {num(kept, 1)}% of normal throughput |")

    o += ["", "## Snapshots", "", "| State size | Take (serialize) | Restore | Save durably + compact |", "|---|---|---|---|"]
    for sv in cur.variants("snapshot_cost"):
        o.append(f"| {sv} | {num(cur.f('snapshot_cost', sv, 'take'), 2)} ms | {num(cur.f('snapshot_cost', sv, 'restore'), 2)} ms | "
                 f"{num(cur.f('snapshot_cost', sv, 'save_durably'), 2)} ms |")
    a1, a0 = cur.f("append_and_sync", "fsync", "per_entry"), cur.f("append_and_sync", "no fsync", "per_entry")
    if a1 and a0:
        o += ["", f"One log append plus sync takes {num(a1)} µs with fsync and {num(a0, 1)} µs without."]

    if base.rows:
        o += ["", "## Before and after the final improvements", "",
              "Phase 9 measured the first complete version. Three changes followed: group commit, an adaptive "
              "client timeout, and PreVote/CheckQuorum.", "",
              "| | Phase 9 | Now |", "|---|---|---|"]
        rows = [("Writes per second, 3 nodes, 32 clients", "cluster_size", "3 nodes", "ops_per_sec", 0, " ops/s"),
                ("Write latency p50, 3 nodes, 32 clients", "cluster_size", "3 nodes", "write_p50", 1, " ms"),
                ("Write latency p99, 3 nodes, 32 clients", "cluster_size", "3 nodes", "write_p99", 1, " ms")]
        for label, e, v, m, d, unit in rows:
            o.append(f"| {label} | {num(base.f(e, v, m), d)}{unit} | {num(cur.f(e, v, m), d)}{unit} |")
        bfv, cfv = base.first_variant("leader_failover"), cur.first_variant("leader_failover")
        o.append(f"| Writes resume after `kill -9` of the leader (median) | {num(base.f('leader_failover', bfv, 'median'))} ms | "
                 f"{num(cur.f('leader_failover', cfv, 'median'))} ms |")
        o.append(f"| 20% message drops (simulated) | {num(base.f('message_drops', '20% drops, simulated', 'throughput_kept'), 1)}% "
                 f"of normal | {num(cur.f('message_drops', '20% drops, simulated', 'throughput_kept'), 1)}% of normal |")

        t3, t5 = base.f("cluster_size", "3 nodes", "ops_per_sec"), base.f("cluster_size", "5 nodes", "ops_per_sec")
        bb1, bb64 = base.f("batching", "max 1 entry per RPC", "ops_per_sec"), base.f("batching", "max 64 entries per RPC", "ops_per_sec")
        fmed, fmax = base.f("leader_failover", bfv, "median"), base.f("leader_failover", bfv, "max")
        if t3 and t5 and bb1 and bb64 and fmax:
            drop, ratio = 100 * (1 - t5 / t3), bb64 / bb1
            o += ["", "## Predictions", "",
                  "Committed in [`raftkv.md`](../raftkv.md) §7 before anything was measured, and scored against the "
                  "Phase 9 measurements, the version they were made about.", "",
                  "| Prediction | Measured | Verdict |", "|---|---|---|",
                  f"| 3 → 5 nodes costs about 25% of write throughput | {drop:.1f}% | "
                  + ("✓ held |" if abs(drop - 25) <= 10 else "✗ wrong: much smaller |"),
                  f"| Writes resume within 1000 ms of `kill -9` of the leader | median {num(fmed)} ms, worst {num(fmax)} ms | "
                  + ("✓ held |" if fmax < 1000 else "✗ wrong |"),
                  f"| Batching gives about 2× | {ratio:.1f}× | "
                  + ("✓ held |" if abs(ratio - 2) <= 0.5 else ("✗ wrong: underestimated |" if ratio > 2 else "✗ wrong: overestimated |"))]
    return "\n".join(o) + "\n"


def readme_summary(cur, base):
    """The README's short, plain-language version."""
    t3 = cur.f("cluster_size", "3 nodes", "ops_per_sec")
    p50 = cur.f("cluster_size", "3 nodes", "write_p50")
    fv = cur.first_variant("leader_failover")
    fail = cur.f("leader_failover", fv, "median")
    g0, g1 = cur.f("group_commit", "off (one fsync per request)", "ops_per_sec"), cur.f("group_commit", "on (one fsync per batch)", "ops_per_sec")
    if t3 is None:
        return "*Not measured yet: run `python3 tools/bench/run_all.py`.*"
    o = [f"Measured on one laptop ({cur.get('machine', 'cpu', 'model')}), with three real server processes. "
         "Full tables, and how they were measured, are in [`docs/results.md`](docs/results.md).", "",
         "| Question | Answer |", "|---|---|",
         f"| How many writes per second can 3 servers handle? | about **{num(t3)}** (32 clients at once) |",
         f"| How long does one write take? | about **{num(p50)} ms** (typical) |",
         f"| If the leader server crashes, how long until writes work again? | about **{num(fail)} ms** |"]
    if g0 and g1:
        o.append(f"| How much did writing to disk in batches help? | **{g1 / g0:.1f}×** more writes per second |")
    o.append("| Did any test ever lose a write the store had confirmed? | **no** |")
    return "\n".join(o)


def main():
    cur, base = Data(CURRENT), Data(BASELINE)
    want_md = results_md(cur, base)
    text = README.read_text()
    if BEGIN not in text or END not in text:
        print("README.md has no results markers", file=sys.stderr)
        return 1
    before, rest = text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    want_readme = f"{before}{BEGIN}\n{readme_summary(cur, base)}\n{END}{after}"

    if "--check" in sys.argv:
        stale = [p for p, want in ((README, want_readme), (RESULTS_MD, want_md))
                 if not p.exists() or p.read_text() != want]
        if stale:
            print("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale) +
                  "; run python3 tools/results_table.py", file=sys.stderr)
            return 1
        print("README.md and docs/results.md match the measurements")
        return 0
    README.write_text(want_readme)
    RESULTS_MD.write_text(want_md)
    print("wrote README.md summary and docs/results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
