#!/usr/bin/env python3
"""Renders docs/results.csv into the README, between the results markers.

    python3 tools/results_table.py          # rewrite the README section
    python3 tools/results_table.py --check  # fail if the README does not match the CSV (CI)

The README's numbers come only from the CSV, which only tools/bench/run_all.py writes, so the
write-up cannot drift from the measurements.
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
CSV = ROOT / "docs/results.csv"
BEGIN = "<!-- results:begin (generated by tools/results_table.py from docs/results.csv; do not edit) -->"
END = "<!-- results:end -->"


def load():
    if not CSV.exists():
        return None
    with open(CSV, newline="") as f:
        rows = list(csv.DictReader(f))
    get = lambda e, v, m: next((r["value"] for r in rows if r["experiment"] == e and r["variant"] == v
                                and r["metric"] == m), None)
    variants = lambda e: list(dict.fromkeys(r["variant"] for r in rows if r["experiment"] == e))
    return get, variants


def num(s, digits=0):
    if s is None:
        return "–"
    v = float(s)
    return f"{v:,.{digits}f}"


def render():
    data = load()
    if data is None:
        return "*Not measured yet: run `python3 tools/bench/run_all.py`.*"
    get, variants = data
    out = []
    out.append(f"Measured on {get('machine', 'cpu', 'model')}, {get('machine', 'cpu', 'cores')} cores, "
               f"{get('machine', 'memory', 'size')} GiB, {get('machine', 'os', 'name')}, "
               f"on {get('machine', 'date', 'measured')}. Real `raftkvd` processes on one machine, driven by "
               "`raftkvload` (closed-loop clients, 16-byte values), durable fsync unless stated. "
               "Throughput figures are the median of three 10 s runs (the build-type rows are single runs). They compare configurations "
               "on this laptop; they are not a claim about production hardware.")
    out.append("")

    out.append("| Cluster size (writes, 32 clients) | Throughput | Write p50 | Write p99 |")
    out.append("|---|---|---|---|")
    for v in variants("cluster_size"):
        out.append(f"| {v} | {num(get('cluster_size', v, 'ops_per_sec'))} ops/s | "
                   f"{num(get('cluster_size', v, 'write_p50'), 2)} ms | {num(get('cluster_size', v, 'write_p99'), 2)} ms |")
    out.append("")

    v = "3 nodes, 50% writes"
    out.append("| Reads vs writes (3 nodes, 8 clients, 50% writes) | p50 | p99 |")
    out.append("|---|---|---|")
    out.append(f"| Get (through the log) | {num(get('read_write_latency', v, 'read_p50'), 2)} ms | "
               f"{num(get('read_write_latency', v, 'read_p99'), 2)} ms |")
    out.append(f"| Put | {num(get('read_write_latency', v, 'write_p50'), 2)} ms | "
               f"{num(get('read_write_latency', v, 'write_p99'), 2)} ms |")
    out.append("")

    rows = []
    for fv in variants("leader_failover"):
        rows.append(f"| Recovery after `kill -9` of the leader ({fv}) | median {num(get('leader_failover', fv, 'median'))} ms, "
                    f"max {num(get('leader_failover', fv, 'max'))} ms |")
    md = "3 nodes, 1 follower stopped"
    three = get("cluster_size", "3 nodes", "ops_per_sec")
    if get("minority_down", md, "ops_per_sec"):
        rows.append(f"| Throughput with one follower stopped (`SIGSTOP`; stands in for a minority partition) | "
                    f"{num(get('minority_down', md, 'ops_per_sec'))} ops/s, vs {num(three)} with all three |")
    b1, b64 = get("batching", "max 1 entry per RPC", "ops_per_sec"), get("batching", "max 64 entries per RPC", "ops_per_sec")
    if b1 and b64:
        rows.append(f"| Batching: up to 64 entries per `AppendEntries` vs 1 | {num(b64)} vs {num(b1)} ops/s "
                    f"(**{float(b64) / float(b1):.2f}×**) |")
    f1, f0 = get("fsync", "durable (fsync)", "ops_per_sec"), get("fsync", "no fsync (unsafe)", "ops_per_sec")
    if f1 and f0:
        rows.append(f"| Cost of durable fsync | {num(f1)} ops/s durable vs {num(f0)} without fsync "
                    f"(**{float(f0) / float(f1):.1f}×**) |")
    for bv in variants("build_type"):
        rows.append(f"| Servers built {bv} | {num(get('build_type', bv, 'ops_per_sec'))} ops/s |")
    kept = get("message_drops", "20% drops, simulated", "throughput_kept")
    if kept:
        rows.append(f"| 20% message drops (simulator, virtual time) | {num(kept, 1)}% of normal throughput |")
    out.append("| Measurement | Result |")
    out.append("|---|---|")
    out.extend(rows)
    out.append("")

    out.append("| Snapshot cost (state size) | Take (serialize) | Restore | Save durably + compact |")
    out.append("|---|---|---|---|")
    for sv in variants("snapshot_cost"):
        out.append(f"| {sv} | {num(get('snapshot_cost', sv, 'take'), 2)} ms | {num(get('snapshot_cost', sv, 'restore'), 2)} ms | "
                   f"{num(get('snapshot_cost', sv, 'save_durably'), 2)} ms |")
    a1, a0 = get("append_and_sync", "fsync", "per_entry"), get("append_and_sync", "no fsync", "per_entry")
    if a1 and a0:
        out.append("")
        out.append(f"One log append plus sync takes {num(a1)} µs with fsync and {num(a0, 1)} µs without, "
                   "which is the floor on every committed write's latency.")

    # The predictions, committed in raftkv.md §7 before any of this was measured.
    t3, t5 = get("cluster_size", "3 nodes", "ops_per_sec"), get("cluster_size", "5 nodes", "ops_per_sec")
    fmax = get("leader_failover", next(iter(variants("leader_failover")), ""), "max")
    fmed = get("leader_failover", next(iter(variants("leader_failover")), ""), "median")
    if t3 and t5 and fmax and b1 and b64:
        drop = 100 * (1 - float(t5) / float(t3))
        ratio = float(b64) / float(b1)
        verdict = lambda ok: "✓ held" if ok else "✗ wrong"
        out.append("")
        out.append("**Predictions**, committed before measuring ([`raftkv.md`](raftkv.md) §7):")
        out.append("")
        out.append("| Prediction | Measured | Verdict |")
        out.append("|---|---|---|")
        out.append(f"| 3 → 5 nodes costs about 25% of write throughput | {drop:.1f}% | "
                   f"{verdict(abs(drop - 25) <= 10)}: much smaller |" if abs(drop - 25) > 10 else
                   f"| 3 → 5 nodes costs about 25% of write throughput | {drop:.1f}% | {verdict(True)} |")
        out.append(f"| Writes resume within 1000 ms of `kill -9` of the leader | median {num(fmed)} ms, max {num(fmax)} ms | "
                   f"{verdict(float(fmax) < 1000)} |")
        out.append(f"| Batching gives about 2× | {ratio:.1f}× | "
                   + (f"{verdict(False)}: {'underestimated' if ratio > 2 else 'overestimated'} |" if abs(ratio - 2) > 0.5
                      else f"{verdict(True)} |"))
        if a1 and f0 and f1:
            ceiling = 1e6 / float(a1)
            out.append("")
            out.append(
                f"**What the numbers say.** Every write is bound by fsync. One append plus `F_FULLFSYNC` takes "
                f"{float(a1) / 1000:.2f} ms, a ceiling of about {ceiling:,.0f} syncs per second, and a single node "
                f"reaches {num(get('cluster_size', '1 node', 'ops_per_sec'))} ops/s: the leader syncs once per "
                f"proposal, with no group commit across concurrent requests. Without fsync the same cluster does "
                f"{num(f0)} ops/s. That is why extra followers cost so little (followers sync in parallel with each other), why sanitizer "
                f"builds are barely slower, and why batching matters more than predicted: with one entry per RPC, "
                f"followers sync once per entry too. Leader recovery is set by the client's 500 ms request timeout, "
                f"not by the election (150–300 ms): the request in flight to the dead leader has to time out first. "
                f"Group commit and a shorter, adaptive client timeout are the two obvious next steps.")
    return "\n".join(out)


def main():
    text = README.read_text()
    if BEGIN not in text or END not in text:
        print("README.md has no results markers", file=sys.stderr)
        return 1
    before, rest = text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    new = f"{before}{BEGIN}\n{render()}\n{END}{after}"
    if "--check" in sys.argv:
        if new != text:
            print("README.md results do not match docs/results.csv; run python3 tools/results_table.py",
                  file=sys.stderr)
            return 1
        print("README results match docs/results.csv")
        return 0
    README.write_text(new)
    print("README results updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
